export const HELP_CATEGORIES = ['All', ...Array.from(new Set(HELP_TOPICS.map((topic) => topic.category)))];

export function searchHelpTopics(query: string, category = 'All'): HelpTopic[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return HELP_TOPICS.filter((topic) => (category === 'All' || topic.category === category) && words.every((word) => JSON.stringify(topic).toLowerCase().includes(word)));
}
